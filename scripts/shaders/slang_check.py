"""CI checks on the generated shaders (they need no GPU).

  interface   the manifest's interface, from slangc's reflection: every fragment input matches a vertex output by
              location and type (names are informational); locations and texture bindings are unique; both stages declare
              the same uniform block members (parsed from the generated text), above the viewer's own UBO bindings;
              a program's texture units are 0..n-1 in a row, and diffuseMap is unit 0;
              every vertex input sits at the slot and name of the viewer's reserved attribute table
  compile     every generated stage compiled and every program linked with glslang as GLSL 4.60 for OpenGL, with the
              loader's define block (see assemble_source) once with every hook 0 and once with every hook 1
  position    the position-module gate: every program takes its position from the one shared module (its vertex
              source imports it and calls its `prefix` functions, the SV_Position field is assigned whole from such a
              call, no other Slang source writes gl_Position), and the module must exist. The hand-written GLSL that
              still writes gl_Position is a shrinking list (glsl_position_baseline.txt): a new file that writes it, or a
              listed file that no longer does, fails.
  manifest    the manifest agrees with the files: hashes, hook lists, header

  python scripts/shaders/slang_check.py all [--generated DIR] [--src-dir DIR] [--glslang PATH]
"""
import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import slang_common as common  # noqa: E402


class CheckError(Exception):
    pass


def assemble_source(stage, text, hook_values):
    """The text the loader hands the driver for a generated stage: #version 460, one #define per hook, the whole file.

    Mirrors LLShaderMgr's generated path (indra/llrender/llgeneratedshader.h); the two are tested against the same
    literal. `hook_values` maps hook name to the value string the loader would define (0 when the viewer sets none)."""
    out = ['#version 460\n']
    for name in common.header_hooks(text):
        out.append(f'#define {name} {hook_values.get(name, "0")}\n')
    out.append(text)
    return ''.join(out)


def load_manifest(generated):
    path = Path(generated) / 'programs.json'
    if not path.is_file():
        raise CheckError(f'{path} missing')
    return json.loads(path.read_text(encoding='utf-8'))


def check_manifest(generated):
    errors = []
    manifest = load_manifest(generated)
    listed = set()
    for prog in manifest['programs']:
        for stage, info in prog['stages'].items():
            listed.add(info['file'])
            path = Path(generated) / info['file']
            if not path.is_file():
                errors.append(f'{info["file"]}: listed in programs.json but missing')
                continue
            data = path.read_bytes()
            if hashlib.sha256(data).hexdigest() != info['sha256']:
                errors.append(f'{info["file"]}: hash differs from programs.json')
            text = data.decode('utf-8')
            if common.header_hooks(text) != info['hooks']:
                errors.append(f'{info["file"]}: hook list in the header differs from programs.json')
            if b'\r' in data:
                errors.append(f'{info["file"]}: carriage return in a generated file')
            if re.search(r'(?m)^#version', text):
                errors.append(f'{info["file"]}: carries its own #version (the loader writes it)')
            if len(text.split('\n', 1)[0]) == 0 or not text.startswith('// Generated by'):
                errors.append(f'{info["file"]}: header missing')
    on_disk = {p.name for p in Path(generated).glob('*.glsl')}
    for extra in sorted(on_disk - listed):
        errors.append(f'{extra}: not in programs.json')
    return errors


BLOCK = re.compile(r'layout\(binding\s*=\s*(\d+)\)\s*layout\(std140\)\s*uniform\s+(\w+)\s*\{(.*?)\}\s*\w*\s*;', re.S)


def block_of(text):
    """(binding, block name, member declarations) of a generated stage's uniform block, or None when it has none."""
    m = BLOCK.search(text)
    if not m:
        return None
    members = [' '.join(x.split()) for x in m.group(3).split(';') if x.strip()]
    return int(m.group(1)), m.group(2), members


def check_interface(generated):
    errors = []
    manifest = load_manifest(generated)
    reserved = common.reserved_attribs()
    first_free = common.reserved_block_count()
    for prog in manifest['programs']:
        pid, stages = prog['id'], prog['stages']
        blocks = {}
        for stage, info in stages.items():
            iface = info['interface']
            if stage == 'vertex':
                for a in iface['inputs']:
                    if a['name'] not in reserved or reserved.index(a['name']) != a['location']:
                        slot = reserved.index(a['name']) if a['name'] in reserved else None
                        errors.append(f'{pid}.vertex: input {a["name"]} at location {a["location"]}, but the viewer reads '
                                      f'attributes by its reserved table (slot {slot})')
            text = (Path(generated) / info['file']).read_text(encoding='utf-8')
            blocks[stage] = block_of(text)
            if blocks[stage] and blocks[stage][0] < first_free:
                errors.append(f'{pid}.{stage}: uniform block at binding {blocks[stage][0]}, inside the viewer own '
                              f'UBO bindings 0 to {first_free - 1}')
            for kind in ('inputs', 'outputs'):
                locs = [i['location'] for i in iface[kind]]
                if len(locs) != len(set(locs)):
                    errors.append(f'{pid}.{stage}: duplicate {kind[:-1]} location')
            binds = [t['binding'] for t in iface['textures']]
            if len(binds) != len(set(binds)):
                errors.append(f'{pid}.{stage}: duplicate texture binding')
            end = 0
            for u in sorted(iface['uniforms'], key=lambda u: u['offset']):
                if u['offset'] < end:
                    errors.append(f'{pid}.{stage}: uniform {u["name"]} overlaps the one before it')
                end = u['offset'] + u['size']
        # texture units: the program's samplers take units 0, 1, 2, ... in declaration order with no gap (a gap wastes a unit
        # and LLGLSLShader::mActiveTextureChannels is the highest unit plus one), and diffuseMap, the sampler the viewer
        # binds first, takes unit 0 (doc/slang.md: declare it first)
        units = {}
        for s, i in stages.items():
            for t in i['interface']['textures']:
                units[t['name']] = t['binding']
        if sorted(units.values()) != list(range(len(units))):
            errors.append(f'{pid}: texture units {sorted(units.values())} are not 0..{len(units) - 1} in a row')
        if 'diffuseMap' in units and units['diffuseMap'] != 0:
            errors.append(f'{pid}: diffuseMap is on texture unit {units["diffuseMap"]}, declare it first (unit 0)')
        if len(stages) > 1:
            present = {s: b for s, b in blocks.items() if b}
            if len({json.dumps(b) for b in present.values()}) > 1:
                errors.append(f'{pid}: the stages declare different uniform blocks (one program, one block)')
            tex = {}
            for s, i in stages.items():
                for t in i['interface']['textures']:
                    if tex.setdefault(t['binding'], t['name']) != t['name']:
                        errors.append(f'{pid}: texture binding {t["binding"]} is two different samplers in two stages')
        if 'vertex' in stages and 'fragment' in stages:
            outs = {o['location']: o for o in stages['vertex']['interface']['outputs']}
            for i in stages['fragment']['interface']['inputs']:
                o = outs.get(i['location'])
                if o is None:
                    errors.append(f'{pid}: fragment input {i["name"]} (location {i["location"]}) has no vertex output')
                elif o['type'] != i['type']:
                    errors.append(f'{pid}: location {i["location"]}: vertex writes {o["name"]} {o["type"]}, '
                                  f'fragment reads {i["name"]} {i["type"]}')  # names may differ: GL links by location
    return errors


def find_glslang(override=None):
    for cand in ([override] if override else []) + [os.environ.get('GLSLANG')]:
        if cand and Path(cand).is_file():
            return str(cand)
    for name in ('glslangValidator', 'glslang'):
        found = shutil.which(name)
        if found:
            return found
    sdk = os.environ.get('VULKAN_SDK')
    if sdk:
        for name in ('glslangValidator', 'glslangValidator.exe'):
            p = Path(sdk) / 'Bin' / name
            if p.is_file():
                return str(p)
    return None


def check_compile(generated, glslang):
    """Compile every stage and link every program with glslang for OpenGL, hooks all 0 and all 1."""
    if not glslang:
        raise CheckError('glslangValidator not found (apt install glslang-tools, or set GLSLANG)')
    errors = []
    manifest = load_manifest(generated)
    for value in ('0', '1'):
        with tempfile.TemporaryDirectory() as tmp:
            for prog in manifest['programs']:
                files = []
                for stage, info in prog['stages'].items():
                    text = (Path(generated) / info['file']).read_text(encoding='utf-8')
                    hooks = {h: value for h in info['hooks']}
                    src = Path(tmp) / f'{prog["id"]}.{common.STAGE_EXT[stage]}'
                    src.write_text(assemble_source(stage, text, hooks), encoding='utf-8', newline='\n')
                    files.append(str(src))
                run = subprocess.run([glslang, '--target-env', 'opengl', '-l', *files], capture_output=True, text=True, cwd=tmp)  # -l may drop .spv files
                if run.returncode != 0:
                    errors.append(f'{prog["id"]} (hooks = {value}): glslang failed\n' + (run.stdout + run.stderr).strip())
    return errors


IMPORT = re.compile(r'(?m)^\s*(?:__)?(?:import|include|implementing)\s+([A-Za-z0-9_.]+)\s*;')


def _module_file(src_dir, name):
    rel = name.replace('.', '/')
    for cand in (rel, rel.replace('_', '-')):
        p = Path(src_dir) / f'{cand}.slang'
        if p.is_file():
            return p
    return None


def _closure(src_dir, start):
    seen, todo = set(), [start]
    while todo:
        p = todo.pop()
        if p in seen:
            continue
        seen.add(p)
        for name in IMPORT.findall(p.read_text(encoding='utf-8')):
            m = _module_file(src_dir, name)
            if m:
                todo.append(m)
    return seen


def _strip_comments(text):
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    return re.sub(r'//[^\n]*', '', text)


GLSL_POSITION = re.compile(r'\bgl_Position\b\s*(?:\.\w+)?\s*[-+*/]?=(?!=)')


def check_glsl_baseline(glsl_root, baseline):
    """The hand-written GLSL that writes gl_Position is a list that only shrinks until the switchover removes the GLSL.

    A new .glsl file that writes it fails (new programs are Slang, through the position module); a listed file that no
    longer writes it, or is gone, fails too, so the list is cut as the conversion goes."""
    root = Path(glsl_root)
    listed = {line.strip() for line in Path(baseline).read_text(encoding='utf-8').splitlines()
              if line.strip() and not line.startswith('#')}
    found = set()
    for path in root.rglob('*.glsl'):
        rel = path.relative_to(root).as_posix()
        if rel.startswith('generated/'):
            continue
        if GLSL_POSITION.search(_strip_comments(path.read_text(encoding='utf-8', errors='replace'))):
            found.add(rel)
    errors = [f'{rel}: hand-written GLSL writes gl_Position; write the program in Slang, through the position module'
              for rel in sorted(found - listed)]
    errors += [f'{rel}: listed in {Path(baseline).name} but no longer writes gl_Position (or is gone); remove the line'
               for rel in sorted(listed - found)]
    return errors


def check_position(src_dir, generated, glsl_root=None, baseline=None):
    """The position-module gate: the module and its list entry must exist, and every program takes its position from it."""
    errors = []
    src_dir = Path(src_dir)
    plist = json.loads((src_dir / 'program_list.json').read_text(encoding='utf-8'))
    position = plist.get('position')
    vertex_programs = [p for p in plist.get('programs', []) if 'vertex' in p['entries']]
    if glsl_root is not None and baseline is not None:
        errors += check_glsl_baseline(glsl_root, baseline)
    if not position:
        return errors + ['program_list.json has no "position" entry naming the shared position module']
    module = _module_file(src_dir, position['module'])
    if module is None:
        return errors + [f'the position module {position["module"]}.slang does not exist']
    prefix = position.get('prefix', 'vkPosition')
    call = re.compile(r'\b' + re.escape(prefix) + r'\w*\s*\(')
    # the whole right-hand side is one call of the module (arguments may nest calls, nothing follows the closing paren)
    whole_call = re.compile(r'\s*' + re.escape(prefix) + r'\w*\s*\((?:[^()]|\((?:[^()]|\([^()]*\))*\))*\)\s*$')
    for slang in sorted(src_dir.rglob('*.slang')):
        if slang.resolve() == module.resolve():
            continue
        text = _strip_comments(slang.read_text(encoding='utf-8'))
        rel = slang.relative_to(src_dir)
        if re.search(r'\bgl_Position\b', text):
            errors.append(f'{rel}: writes gl_Position; the position comes from {position["module"]} only')
        if re.search(r'\)\s*:\s*SV_Position\b', text):
            errors.append(f'{rel}: returns SV_Position straight from a function; return a struct whose field is '
                          f'assigned from {prefix}*()')
        # an SV_Position field may only be assigned from a call of the module's functions, whole and with plain `=`
        for field in set(re.findall(r'\b(\w+)\s*:\s*SV_Position\b', text)):
            for m in re.finditer(r'\b' + re.escape(field) + r'((?:\.\w+)*)\s*([-+*/%&|^]?=)(?!=)([^;]*);', text):
                if m.group(1) or m.group(2) != '=' or not whole_call.match(m.group(3)):
                    errors.append(f'{rel}: {field}{m.group(1)} {m.group(2)} {m.group(3).strip()[:40]}: the SV_Position field '
                                  f'must be assigned whole from a {prefix}*() call')
    for prog in vertex_programs:
        main = src_dir / prog['source']
        files = _closure(src_dir, main)
        if module.resolve() not in {p.resolve() for p in files}:
            errors.append(f'{prog["name"]}: its vertex stage does not take its position from {position["module"]}')
        elif not any(call.search(_strip_comments(p.read_text(encoding='utf-8')))
                     for p in files if p.resolve() != module.resolve()):
            errors.append(f'{prog["name"]}: imports {position["module"]} but never calls {prefix}*()')
    # the module's default for `invariant gl_Position` (VK_POSITION_INVARIANT): when on, every vertex stage declares it
    default = re.search(r'(?m)^#define\s+VK_POSITION_INVARIANT\s+(\d)', module.read_text(encoding='utf-8'))
    invariant = bool(default and default.group(1) == '1')
    manifest = load_manifest(generated)
    for prog in manifest['programs']:
        info = prog['stages'].get('vertex')
        if not info:
            continue
        text = (Path(generated) / info['file']).read_text(encoding='utf-8')
        if len(re.findall(r'\bgl_Position(?:\.\w+)?\s*[-+*/]?=(?!=)', text)) != 1:
            errors.append(f'{info["file"]}: gl_Position must be written exactly once')
        if invariant and not re.search(r'(?m)^invariant gl_Position;', text):
            errors.append(f'{info["file"]}: the position module makes gl_Position invariant, but the stage does not declare it')
    return errors


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('check', choices=['manifest', 'interface', 'compile', 'position', 'all'])
    ap.add_argument('--generated', default=str(common.GENERATED))
    ap.add_argument('--src-dir', default=str(common.SLANG_SRC))
    ap.add_argument('--glslang')
    ap.add_argument('--glsl-root', default=str(common.LEGACY_SHADERS))
    ap.add_argument('--glsl-baseline', default=str(Path(__file__).resolve().with_name('glsl_position_baseline.txt')))
    args = ap.parse_args()
    which = ['manifest', 'interface', 'position', 'compile'] if args.check == 'all' else [args.check]
    failed = False
    for name in which:
        try:
            if name == 'manifest':
                errs = check_manifest(args.generated)
            elif name == 'interface':
                errs = check_interface(args.generated)
            elif name == 'position':
                errs = check_position(args.src_dir, args.generated, args.glsl_root, args.glsl_baseline)
            else:
                errs = check_compile(args.generated, find_glslang(args.glslang))
        except CheckError as e:
            errs = [str(e)]
        print(f'{name}: ' + ('ok' if not errs else f'{len(errs)} problem(s)'))
        for e in errs:
            print('  ' + e)
        failed |= bool(errs)
    sys.exit(1 if failed else 0)


if __name__ == '__main__':
    main()
