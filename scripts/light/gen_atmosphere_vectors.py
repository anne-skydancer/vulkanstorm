"""Evaluate the viewer's atmosphericsFuncs.glsl on the GPU for fixed pseudo-random inputs and write
indra/newview/tests/llatmosphericlight_vectors.inc, the vectors that llatmosphericlight_test.cpp
holds llatmosphericlight.h to (stage L1 of the light study). CI runs only the C++ test; this script
is what ties the vectors to the GLSL.

    python scripts/light/gen_atmosphere_vectors.py            # rewrite the .inc file
    python scripts/light/gen_atmosphere_vectors.py --check    # fail if the GLSL no longer produces it

Needs Windows and a GPU. The viewer's GLSL is float, so --check allows 1e-4 relative.
"""
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from atmosphere_gl import *  # noqa: E402,F401,F403

OUT = ROOT / 'indra' / 'newview' / 'tests' / 'llatmosphericlight_vectors.inc'
N = 96

MAIN = """
uniform vec3 vec_norm;
layout(location = 0) out vec4 out_sunlit;
layout(location = 1) out vec4 out_amblit;
void main() {
    vec3 sunlit, amblit, additive, atten;
    calcAtmosphericVarsLinear(vec3(0.0, 0.0, -100.0), vec3(sqrt(max(0.0, 1.0 - vec_norm.z * vec_norm.z)), 0.0, vec_norm.z),
                              vec3(0.0, 0.0, 1.0), sunlit, amblit, additive, atten);
    out_sunlit = vec4(sunlit, 1.0);
    out_amblit = vec4(amblit, 1.0);
}
"""


def cases():
    rnd = random.Random(20261108)
    u = rnd.random
    out = []
    for i in range(N):
        out.append(dict(
            sunlight_color=[round(u() * 2.0, 4) for _ in range(3)], moonlight_color=[round(u() * 0.5, 4) for _ in range(3)],
            primary_light_color=[round(u() * 1.5, 4) for _ in range(3)],
            sun_up=1 if i % 5 else 0, ambient=[round(u() * 1.2, 4) for _ in range(3)],
            blue_density=[round(0.05 + u() * 0.95, 4) for _ in range(3)], blue_horizon=[0.5, 0.5, 0.6],
            haze_density=round(u() * 1.5, 4), haze_horizon=0.19, cloud_shadow=round(u(), 4) if i % 3 else 0.0,
            density_multiplier=round(u() * 0.0005, 6), distance_multiplier=0.8, max_y=round(100 + u() * 3900, 1),
            glow=[5.0, 0.001, -0.5], light_y=round(0.005 + u() * 0.995, 4),
            sky_sunlight_scale=rnd.choice([1.0, 1.0, 1.5]), sky_ambient_scale=rnd.choice([1.0, 1.0, 1.5]),
            classic_mode=i % 2, n_dot_l=round(u() * 2.0 - 1.0, 4)))
    return out


def evaluate(cs):
    prog = atmosphere_program(MAIN)
    tgt = Target(1, 2)
    res = []
    for c in cs:
        tgt.bind(); use(prog); set_atmosphere_uniforms(prog, c)
        uniform(prog, 'vec_norm', 0.0, 0.0, c['n_dot_l'])
        draw(0x0004, 0, 3)
        res.append((tgt.read(0)[0][:3], tgt.read(1)[0][:3]))
    return res


def render(cs, res):
    lines = ['// SPDX-License-Identifier: GPL-3.0-or-later', '// Copyright (C) 2026, Anne Skydancer (Vulkanstorm)',
             '// Generated by scripts/light/gen_atmosphere_vectors.py from atmosphericsFuncs.glsl on the GPU; do not edit.',
             '// {primary_light_color rgb, ambient rgb, cloud_shadow, sky_sunlight_scale, sky_ambient_scale, classic_mode, n_dot_l,',
             '//  expected sunlit rgb, expected amblit rgb}']
    for c, (s, a) in zip(cs, res):
        v = c['primary_light_color'] + c['ambient'] + [c['cloud_shadow'],
            c['sky_sunlight_scale'], c['sky_ambient_scale'], c['classic_mode'], c['n_dot_l']] + list(s) + list(a)
        lines.append('{ ' + ', '.join(str(x) if isinstance(x, int) else repr(float(x)) for x in v) + ' },')
    return '\n'.join(lines) + '\n'


def numbers(text):
    return [float(x) for line in text.splitlines() if line.startswith('{') for x in line.strip('{ },').split(',')]


cs = cases()
text = render(cs, evaluate(cs))
if '--check' in sys.argv:
    old, new = numbers(OUT.read_text()), numbers(text)
    bad = [(i, a, b) for i, (a, b) in enumerate(zip(old, new)) if abs(a - b) > 1e-4 * max(abs(a), abs(b)) + 1e-6]
    print('numbers:', len(new), 'mismatches:', len(bad), bad[:5])
    sys.exit(1 if bad or len(old) != len(new) else 0)
OUT.write_text(text)
print('wrote', OUT, len(cs), 'vectors')
