# --- noise generation (clouds.wgsl gen_base, gen_detail, gen_curl), fragment per layer --
NOISE = """
uint hash_u(uint x) { uint v = x * 747796405u + 2891336453u; uint w = ((v >> ((v >> 28u) + 4u)) ^ v) * 277803737u; return (w >> 22u) ^ w; }
uint hash3(ivec3 c) { return hash_u(uint(c.x) ^ hash_u(uint(c.y) ^ hash_u(uint(c.z) + 0x9e3779b9u))); }
vec3 rand3(ivec3 c) { uint h = hash3(c); return vec3(float(h & 1023u), float((h >> 10u) & 1023u), float((h >> 20u) & 1023u)) / 1023.0; }
// (c + 8p) % p: GLSL leaves % of negative operands undefined; c >= -1 here
ivec3 wrap3(ivec3 c, int p) { return (c + ivec3(8 * p)) % p; }
float grad3(ivec3 c, vec3 f) { vec3 g = rand3(c) * 2.0 - 1.0; return dot(normalize(g + vec3(1e-4)), f); }
float perlin3(vec3 p, int period) {
    ivec3 i = ivec3(floor(p)); vec3 f = fract(p); vec3 w = f * f * f * (f * (f * 6.0 - 15.0) + 10.0);
    float n000 = grad3(wrap3(i + ivec3(0,0,0), period), f - vec3(0,0,0)); float n100 = grad3(wrap3(i + ivec3(1,0,0), period), f - vec3(1,0,0));
    float n010 = grad3(wrap3(i + ivec3(0,1,0), period), f - vec3(0,1,0)); float n110 = grad3(wrap3(i + ivec3(1,1,0), period), f - vec3(1,1,0));
    float n001 = grad3(wrap3(i + ivec3(0,0,1), period), f - vec3(0,0,1)); float n101 = grad3(wrap3(i + ivec3(1,0,1), period), f - vec3(1,0,1));
    float n011 = grad3(wrap3(i + ivec3(0,1,1), period), f - vec3(0,1,1)); float n111 = grad3(wrap3(i + ivec3(1,1,1), period), f - vec3(1,1,1));
    float x0 = mix(mix(n000, n100, w.x), mix(n010, n110, w.x), w.y); float x1 = mix(mix(n001, n101, w.x), mix(n011, n111, w.x), w.y);
    return mix(x0, x1, w.z) * 0.6 + 0.5;
}
float worley3(vec3 p, int period) {
    ivec3 i = ivec3(floor(p)); vec3 f = fract(p); float d = 1e9;
    for (int z = -1; z <= 1; z++) for (int y = -1; y <= 1; y++) for (int x = -1; x <= 1; x++) {
        ivec3 o = ivec3(x, y, z); vec3 fp = vec3(o) + rand3(wrap3(i + o, period)) - f; d = min(d, dot(fp, fp)); }
    return 1.0 - clamp(sqrt(d), 0.0, 1.0);
}
float worley_fbm(vec3 p, int f) { return worley3(p * float(f), f) * 0.625 + worley3(p * float(2 * f), 2 * f) * 0.25 + worley3(p * float(4 * f), 4 * f) * 0.125; }
float remap(float v, float lo, float hi, float nlo, float nhi) { return nlo + (v - lo) * (nhi - nlo) / (hi - lo); }
"""
GEN_BASE = "#version 400 core\n" + NOISE + """
uniform int z; uniform float n; out vec4 o;
void main() {
    vec3 p = (vec3(gl_FragCoord.xy, float(z) + 0.5)) / n;
    float pf = 0.0, amp = 1.0, tot = 0.0; int fr = 4;
    for (int k = 0; k < 4; k++) { pf += amp * perlin3(p * float(fr), fr); tot += amp; amp *= 0.5; fr *= 2; }
    pf = clamp((pf / tot - 0.5) * 1.8 + 0.5, 0.0, 1.0);
    float w0 = worley_fbm(p, 4), w1 = worley_fbm(p, 8), w2 = worley_fbm(p, 16);
    o = vec4(clamp(remap(pf, w0 - 1.0, 1.0, 0.0, 1.0), 0.0, 1.0), w0, w1, w2);
}"""
GEN_DETAIL = "#version 400 core\n" + NOISE + """
uniform int z; uniform float n; out vec4 o;
void main() { vec3 p = (vec3(gl_FragCoord.xy, float(z) + 0.5)) / n; o = vec4(worley_fbm(p, 2), worley_fbm(p, 4), worley_fbm(p, 8), 1.0); }"""
GEN_CURL = "#version 400 core\n" + NOISE + """
uniform float n; out vec4 o;
void main() {
    vec2 p = gl_FragCoord.xy / n * 8.0; float e = 0.05;
    float dx = perlin3(vec3(p + vec2(e, 0.0), 0.5), 8) - perlin3(vec3(p - vec2(e, 0.0), 0.5), 8);
    float dy = perlin3(vec3(p + vec2(0.0, e), 0.5), 8) - perlin3(vec3(p - vec2(0.0, e), 0.5), 8);
    vec2 c = vec2(dy, -dx) / (2.0 * e); o = vec4(clamp(c * 0.5 + 0.5, 0.0, 1.0), 0.0, 1.0);
}"""

# Stand-in EEP cloud texture: tileable value-noise fbm (Aurora's demo does the same).
CLOUD_TEX = """
float vhash(ivec2 c) { uint h = uint(c.x) * 73856093u ^ uint(c.y) * 19349663u; h = (h ^ (h >> 13u)) * 1274126177u; return float(h & 65535u) / 65535.0; }
float vnoise(vec2 p, int period) { ivec2 i = ivec2(floor(p)); vec2 f = fract(p); f = f * f * (3.0 - 2.0 * f);
    ivec2 a = (i + ivec2(8 * period)) % period, b = (i + ivec2(1) + ivec2(8 * period)) % period;
    return mix(mix(vhash(a), vhash(ivec2(b.x, a.y)), f.x), mix(vhash(ivec2(a.x, b.y)), vhash(b), f.x), f.y); }
float cloud_noise(vec2 uv) { float s = 0.0, a = 0.5; int per = 4; for (int k = 0; k < 4; k++) { s += a * vnoise(uv * float(per), per); a *= 0.5; per *= 2; } return s / 0.9375; }
"""
# env.wgsl fs_cloud_weather (R: coverage, B: detail tap)
GEN_WEATHER = "#version 400 core\n" + CLOUD_TEX + """
uniform float cloud_shadow; uniform float detail_weight; out vec4 o;
const float HEAP_KNEE = 0.4, HEAP_SLOPE = 0.2;
void main() {
    vec2 uv = gl_FragCoord.xy / 512.0;
    float density = 2.0 * (cloud_shadow - 0.25);
    float n1 = cloud_noise(uv) - 0.5; float detail = cloud_noise(uv * 8.0);
    float fine = n1 + (detail - 0.5) * detail_weight * 0.35;
    float wc0 = smoothstep(-0.05, 0.45, fine + density);
    float gc = smoothstep(0.0, 1.0, clamp((cloud_shadow - 0.1) / 0.56, 0.0, 1.0));
    float wc1 = 0.55 + 0.45 * smoothstep(-0.25, 0.25, fine);
    float sheet = clamp((gc - 0.5) * 2.0, 0.0, 1.0);
    float heaps = mix(min(wc0, HEAP_KNEE) + max(wc0 - HEAP_KNEE, 0.0) * HEAP_SLOPE, wc0, sheet);
    o = vec4(mix(heaps, wc1, sheet), 0.0, detail, 0.0);
}"""
