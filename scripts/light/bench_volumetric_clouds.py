def mean_channel(t, w, h, ch):
    bindtex(TEX2D, t); px = (F * (w * h * 4))(); getteximage(TEX2D, 0, 0x1908, 0x1406, px)
    return sum(px[i + ch] for i in range(0, w * h * 4, 4 * 7)) / len(range(0, w * h * 4, 4 * 7))
TEX2D, TEX3D = 0x0DE1, 0x806F
RGBA8, RGBA16F, R16F = 0x8058, 0x881A, 0x822D
LINEAR, REPEAT, CLAMP = 0x2601, 0x2901, 0x812F
FB, COLOR0 = 0x8D40, 0x8CE0
TIME_ELAPSED, QUERY_RESULT = 0x88BF, 0x8866

