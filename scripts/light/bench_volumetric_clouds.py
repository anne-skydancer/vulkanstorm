# --- clouds.rs parameter mapping ---------------------------------------------------------
def smooth(x): return x * x * (3.0 - 2.0 * x)
def coverage(cs): return smooth(min(max((cs - 0.1) / 0.56, 0.0), 1.0))
def cloud_type(cov): return smooth(min(max((0.86 - cov) / (0.86 - 0.38), 0.0), 1.0))
def layer_km(kind):
    pick = lambda lo, mid, hi: lo + (mid - lo) * kind * 2.0 if kind < 0.5 else mid + (hi - mid) * (kind - 0.5) * 2.0
    return pick(0.4, 0.6, 1.2), pick(0.9, 1.25, 2.0)
def tile_km(scale):
    wanted = 105.0 / 8.0 * min(max(scale / 0.42, 0.5), 2.0); n = max(round(105.0 / wanted), 1.0); return 105.0 / n

