"""Offline GPU benchmark for the light study (doc/light/light-model-study.md), no viewer launch.

It answers two questions with GL_TIME_ELAPSED medians:

1. What does Aurora's volumetric cloud trace cost on OpenGL, and is a fragment-shader port
   (GL 4.0, no compute, no image load/store) as fast as a compute port (GL 4.3)?
2. What do ground cloud shadows cost: building a 2D cloud transmittance map (from the flat
   EEP layer's alpha1, or by marching the volumetric layer along the sun) and looking it up
   once per pixel in a full-screen lighting pass?

The cloud model is a GLSL transcription of Aurora Viewer's volumetric clouds
(crates/aurora-render/src/shaders/clouds.wgsl and env.wgsl fs_cloud_weather, branch
feat/volumetric-clouds at 7d480ee1, GPL-3.0-or-later, by Anne Skydancer), after
Schneider & Vos 2015 (Nubis) and Hillaire 2016. The parameter mapping (coverage, cloud
type, layer heights, tile size) follows clouds.rs. The EEP cloud texture is replaced by a
tileable value-noise stand-in, as Aurora's demo does; cost depends on how much of the
layer is cloud, so four covers are timed (fair, broken, stratocumulus, overcast).

Passes timed:
  noise      the 128^3 Perlin-Worley base noise, 32^3 detail, 128^2 curl, generated by
             fragment passes into 3D texture layers (Aurora: compute, a slice a frame)
  weather    the 512^2 weather map (when the sky changes, not per frame)
  trace-frag a quarter of the half-resolution pixels a frame (W/4 x H/4 fragments),
             64 steps and 5 light taps (Aurora's Medium), fragment shader, 2 MRT outputs
  trace-comp the same in a compute shader writing rgba16f images (GL 4.3)
  recon      the half-resolution temporal reconstruction (fragment)
  composite  the full-resolution blend dst*T + L (fragment)
  vshadow    a 512^2 cloud transmittance map marched through the volumetric layer along
             the sun, 16 cheap-density steps per texel
  fshadow    a 512^2 transmittance map from the flat layer's alpha1 (cloudsF.glsl taps)
  lookup     one bilinear tap of a 512^2 map per pixel at W x H, minus an identical pass
             without the tap

Every pixel is treated as sky (worst case: in the viewer only sky pixels are traced).
Two views: "horizon" (the camera 12 degrees up, 60 degree vertical field of view: the lower
part of the screen is below the horizon and returns at once) and "zenith" (60 degrees up:
every ray crosses the layer).

Environment: CLOUD_BENCH_SIZES (default "1920x1080,2560x1440"), CLOUD_BENCH_FRAMES (20).
Pass --opengl PATH to select another GL DLL.
"""
